// HTTP transport for enquire-mcp.
//
// v2.6.0 — remote-MCP support. Runs the MCP server over Streamable HTTP
// (the protocol claude.ai web, ChatGPT, mobile clients, and Cursor's HTTP
// mode all use). Three layers in front of the SDK transport:
//
//   1. Origin admission — a present Origin must exactly match an explicit
//      --cors-origin entry or the request fails with 403 before any route,
//      auth, rate, body, or MCP work. Missing Origin is accepted for native
//      MCP clients. Wildcard and opaque origins are rejected at startup.
//   2. Bearer auth — constant-time token compare, fail-closed (401 on
//      missing/wrong header). Token is generated by the user (we never
//      mint tokens — this is not OAuth) and passed via --bearer-token or
//      --bearer-token-env. See docs/http-transport.md for the security
//      model and Tailscale Funnel / Cloudflare Tunnel deployment recipes.
//   3. Rate-limit — per-token sliding-window bucket, 429 on overflow.
//      In-memory; survives a single process. Default 120 req/min.
//   4. CORS response headers — an admitted explicit origin receives the
//      matching browser grant. Default empty: requests without Origin still
//      work, while every browser-originated request fails admission.
//
// We use the SDK's StreamableHTTPServerTransport in stateless mode
// (sessionIdGenerator: undefined). A fresh transport + McpServer is
// connected per request. The Vault, FtsIndex, EmbedDb handles are
// SHARED across all sessions — opening SQLite once and reusing across
// thousands of remote-MCP calls. This is why prepareServerDeps() is
// called once in startHttpServer() and buildMcpServer() is called per
// request: the heavy I/O happens once at boot.
//
// Stateless is the DEFAULT (our tools are short-running — search, read,
// frontmatter ops), and the right choice for most deployments. Stateful,
// sessionId-keyed transports shipped in v2.14.0 as an opt-in (`stateful: true`):
// a session registry keys requests by an assigned `Mcp-Session-Id`, evicts
// sessions idle past a configurable TTL, tracks `pendingInits`/`inFlight`
// refcounts to avoid mid-request teardown, and drains under a bounded graceful
// shutdown. Enable it only when a client needs sticky per-session state.

